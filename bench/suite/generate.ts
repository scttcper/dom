// Generates the Vitest end-to-end fixture project: N small React test files in
// bench/suite/.generated/ (a dot directory, so `tsc -p` at the root does not type-check them).
// Modeled on ~/gh/jsdom-startup/scripts/generate-fixtures.mjs: short tests keep per-file
// environment/startup cost visible, the way it is in real component suites.

import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

export const generatedDir = fileURLToPath(new URL("./.generated/", import.meta.url));

export function generate(count = 100): void {
  rmSync(generatedDir, { recursive: true, force: true });
  mkdirSync(generatedDir, { recursive: true });
  for (let index = 1; index <= count; index++) {
    const id = String(index).padStart(3, "0");
    // Three shapes rotate so the suite is not one hot path: static render + role queries,
    // a stateful click, and a small labelled form typed into with user-event.
    const kind = index % 3;
    let body: string;
    if (kind === 0) {
      body = `function AccountCard({ name, count }: { name: string; count: number }) {
  return (
    <section aria-label="Account ${id}">
      <h2>{name}</h2>
      <p>Owner: team-${id}</p>
      <button type="button">Messages: {count}</button>
    </section>
  );
}

test("renders account card ${id}", () => {
  render(<AccountCard name="Account ${id}" count={${index}} />);
  expect(screen.getByRole("heading", { name: "Account ${id}" })).toBeInTheDocument();
  expect(screen.getByRole("button", { name: "Messages: ${index}" })).toBeVisible();
  expect(screen.getByText("Owner: team-${id}")).toBeInTheDocument();
});
`;
    } else if (kind === 1) {
      body = `function Counter() {
  const [count, setCount] = useState(${index});
  return (
    <div>
      <output aria-label="count ${id}">{count}</output>
      <button type="button" onClick={() => setCount((c) => c + 1)}>Increment ${id}</button>
    </div>
  );
}

test("increments counter ${id}", async () => {
  const user = userEvent.setup();
  render(<Counter />);
  await user.click(screen.getByRole("button", { name: "Increment ${id}" }));
  expect(screen.getByLabelText("count ${id}")).toHaveTextContent("${index + 1}");
});
`;
    } else {
      body = `function Signup({ onSubmit }: { onSubmit: (v: string) => void }) {
  const [email, setEmail] = useState("");
  return (
    <form onSubmit={(e) => { e.preventDefault(); onSubmit(email); }}>
      <label htmlFor="email-${id}">Email ${id}</label>
      <input id="email-${id}" type="email" value={email} onChange={(e) => setEmail(e.target.value)} />
      <label><input type="checkbox" defaultChecked /> Subscribe</label>
      <button type="submit">Sign up</button>
    </form>
  );
}

test("submits signup form ${id}", async () => {
  const user = userEvent.setup();
  let submitted = "";
  render(<Signup onSubmit={(v) => (submitted = v)} />);
  await user.type(screen.getByLabelText("Email ${id}"), "u${id}@example.com");
  expect(screen.getByRole("checkbox", { name: "Subscribe" })).toBeChecked();
  await user.click(screen.getByRole("button", { name: "Sign up" }));
  expect(submitted).toBe("u${id}@example.com");
  expect(await screen.findByDisplayValue("u${id}@example.com")).toHaveValue("u${id}@example.com");
});
`;
    }
    const source = `// Generated by bench/suite/generate.ts — do not edit.
import { useState } from "react";
import { render, screen } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { expect, test } from "vitest";

void useState;
void userEvent;

${body}`;
    writeFileSync(join(generatedDir, `${id}.test.tsx`), source);
  }
}

if (import.meta.main) {
  const count = Number(process.argv[2] ?? 100);
  generate(count);
  console.log(`generated ${count} test files in ${generatedDir}`);
}
