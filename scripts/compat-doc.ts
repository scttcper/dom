// `pnpm docs:compat`: render the compat profile table of docs/deviations.md from COMPAT
// (packages/dom/src/window/compat.ts). tests/compat/test/surface/profiles.test.ts fails when the
// committed table is out of date.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { COMPAT, COMPAT_PROFILES } from "../packages/dom/src/window/compat.ts";

export const DEVIATIONS = fileURLToPath(new URL("../docs/deviations.md", import.meta.url));
const START = "<!-- compat:start (generated by `pnpm docs:compat` from packages/dom/src/window/compat.ts) -->";
const END = "<!-- compat:end -->";

const code = (s: string) => `\`${s}\``;

function list(names: readonly string[], max: number): string {
  const shown = names.slice(0, max).map(code).join(", ");
  return names.length > max ? `${shown} and ${names.length - max} more` : shown;
}

/** "HTMLElement.popover", ... → "`popover`, `showPopover` on HTMLElement; ..." */
function members(keys: readonly string[]): string {
  const byInterface = new Map<string, string[]>();
  for (const key of keys) {
    const [iface, ...rest] = key.split(".");
    const name = rest.join(".").replace(/^static\./, "static ");
    byInterface.set(iface, [...(byInterface.get(iface) ?? []), name]);
  }
  const groups = [...byInterface];
  // Members repeated on several interfaces (event handlers) read better as one list.
  const first = groups[0][1].join();
  if (groups.length > 1 && groups.every(([, names]) => names.join() === first)) {
    return `${list(groups[0][1], 4)} on ${groups.map(([iface]) => iface).join(", ")}`;
  }
  const shown = groups.slice(0, 6).map(([iface, names]) => `${iface}: ${list(names, 4)}`);
  return groups.length > 6 ? `${shown.join("; ")}; and members of ${groups.length - 6} more interfaces` : shown.join("; ");
}

export function renderCompatTable(): string {
  const rows = [
    `| APIs | ${COMPAT_PROFILES.join(" | ")} | Why |`,
    `| --- | ${COMPAT_PROFILES.map(() => ":-:").join(" | ")} | --- |`,
  ];
  for (const entry of COMPAT) {
    const apis = [entry.globals?.length ? `globals ${list(entry.globals, 8)}` : "", entry.members?.length ? members(entry.members) : ""].filter(Boolean).join("; members ");
    const marks = COMPAT_PROFILES.map((p) => (entry.profiles.includes(p) ? "yes" : "–"));
    rows.push(`| ${apis.startsWith("globals") ? apis : `members ${apis}`} | ${marks.join(" | ")} | ${entry.reason.replaceAll("|", "\\|")} |`);
  }
  return [START, ...rows, END].join("\n");
}

/** docs/deviations.md with the generated table replaced (throws if the markers are missing). */
export function renderDeviations(current: string): string {
  const start = current.indexOf(START);
  const end = current.indexOf(END);
  if (start === -1 || end === -1) throw new Error(`docs/deviations.md: missing ${START} … ${END}`);
  return current.slice(0, start) + renderCompatTable() + current.slice(end + END.length);
}

if (import.meta.main) {
  writeFileSync(DEVIATIONS, renderDeviations(readFileSync(DEVIATIONS, "utf8")));
  console.log("docs/deviations.md: compat table updated");
}
