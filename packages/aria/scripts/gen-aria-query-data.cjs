// Generates src/data/aria-query.generated.ts from aria-query@5.3.0 (the version
// @testing-library/dom@10.4.2 pins). aria-query is Apache-2.0, (c) A11yance.
// Usage: node packages/aria/scripts/gen-aria-query-data.cjs <path-to-aria-query@5.3.0>
//
// Stores `roles`, `aria` and `dom` in a compact form that src/data/aria-query.ts expands;
// `elementRoles` and `roleElements` are derived from `roles` there, as aria-query does.
"use strict";
const fs = require("node:fs");
const path = require("node:path");
const dir = path.resolve(process.argv[2]);
const aq = require(dir);
const pkg = require(path.join(dir, "package.json"));

const aria = [];
for (const [name, def] of aq.aria.entries()) aria.push([name, def]);
const ariaIndex = new Map(aria.map(([name], i) => [name, i]));

// Values that repeat across roles (nameFrom, superClass, props key lists) are stored once in
// `lists` and referenced by index.
const lists = [];
const listIndex = new Map();
function intern(value) {
  const key = JSON.stringify(value);
  if (!listIndex.has(key)) listIndex.set(key, lists.push(value) - 1);
  return listIndex.get(key);
}
// A `{ concept, module }` relation (in that key order) is stored as `[concept, module]`, and a
// concept that is only `{ name }` as the name.
const concept = (c) => (Object.keys(c).join() === "name" ? c.name : c);
const relation = (r) => (Object.keys(r).join() === "concept,module" ? [concept(r.concept), r.module] : r);

// Each role is a tuple (see RawRole in src/data/aria-query.ts). Fail loudly when an
// aria-query release breaks an assumption the compact form relies on.
const KEYS =
  "abstract,accessibleNameRequired,baseConcepts,childrenPresentational,nameFrom,prohibitedProps,props," +
  "relatedConcepts,requireContextRole,requiredContextRole,requiredOwnedElements,requiredProps,superClass";
const roles = aq.roles.entries().map(([name, def]) => {
  if (Object.keys(def).join() !== KEYS) throw new Error(`${name}: unexpected keys ${Object.keys(def)}`);
  if (def.baseConcepts.length !== 0) throw new Error(`${name}: baseConcepts is not empty`);
  if (JSON.stringify(def.requireContextRole) !== JSON.stringify(def.requiredContextRole)) {
    throw new Error(`${name}: requireContextRole differs from requiredContextRole`);
  }
  // props: its keys as indexes into `aria`, plus the values that are not null. The loader
  // splices the keys into JSON text unescaped.
  const propKeys = Object.keys(def.props).map((key) => {
    if (!ariaIndex.has(key) || !/^[a-z-]+$/.test(key)) throw new Error(`${name}: unexpected prop ${key}`);
    return ariaIndex.get(key);
  });
  const values = Object.entries(def.props).filter(([, v]) => v !== null);
  const flags = +def.abstract | (+def.accessibleNameRequired << 1) | (+def.childrenPresentational << 2);
  const tuple = [
    name,
    flags,
    intern(def.nameFrom),
    def.prohibitedProps,
    intern(propKeys),
    def.relatedConcepts.map(relation),
    def.requiredContextRole,
    def.requiredOwnedElements,
    def.requiredProps,
    intern(def.superClass),
  ];
  if (values.length > 0) tuple.push(Object.fromEntries(values));
  return tuple;
});

// `dom` entries are all `{ reserved: boolean }`: stored as names, reserved ones prefixed "!".
const dom = [];
for (const [name, def] of aq.dom.entries()) {
  if (Object.keys(def).join() !== "reserved") throw new Error(`dom ${name}: unexpected keys`);
  dom.push(def.reserved ? `!${name}` : name);
}

const elementRoles = [];
for (const [concept, set] of aq.elementRoles.entries()) elementRoles.push([concept, [...set]]);
const roleElements = [];
for (const [role, set] of aq.roleElements.entries()) roleElements.push([role, [...set]]);

// Testing Library builds selectors from tag names and attributes. A tag is sufficient when
// every entry gives it the same role and at least one entry has no attribute constraint.
const conceptsByTag = Map.groupBy(elementRoles, ([concept]) => concept.name);
const roleTags = roleElements.map(([role, concepts]) => {
  const fixed = [];
  const conditional = [];
  for (const name of new Set(concepts.map((c) => c.name))) {
    const entries = conceptsByTag.get(name);
    const always = entries.every(([, roles]) => roles[0] === role) && entries.some(([c]) => !c.attributes?.length);
    (always ? fixed : conditional).push(name);
  }
  return [role, [fixed, conditional]];
});
const json = JSON.stringify({ lists, roles, aria, dom });
const out = `// GENERATED by packages/aria/scripts/gen-aria-query-data.cjs from aria-query@${pkg.version}.
// Do not edit. Data from aria-query (https://github.com/A11yance/aria-query), Copyright 2020
// A11yance, licensed under the Apache License, Version 2.0
// (http://www.apache.org/licenses/LICENSE-2.0, also in NOTICE); converted to JSON.
// Stored as a JSON string: parsed lazily on first use (JSON.parse beats an object literal).

export const ARIA_QUERY_VERSION = ${JSON.stringify(pkg.version)};

// Lightweight prefilter for ByRole, usable before the full dataset is parsed.
export const ROLE_TAGS = new Map<string, [fixed: string[], conditional: string[]]>(${JSON.stringify(roleTags)});

export const ARIA_QUERY_DATA = ${JSON.stringify(json)};
`;
fs.writeFileSync(path.join(__dirname, "../src/data/aria-query.generated.ts"), out);
console.log("wrote", out.length, "bytes");
