// Generates src/data/aria-query.generated.ts from aria-query@5.3.0 (the version
// @testing-library/dom@10.4.2 pins). aria-query is Apache-2.0, (c) A11yance.
// Usage: node packages/aria/scripts/gen-aria-query-data.cjs <path-to-aria-query@5.3.0>
"use strict";
const fs = require("node:fs");
const path = require("node:path");
const aq = require(path.resolve(process.argv[2]));
const pkg = require(path.resolve(process.argv[2], "package.json"));

const roles = [];
for (const [name, def] of aq.roles.entries()) roles.push([name, def]);
const elementRoles = [];
for (const [concept, set] of aq.elementRoles.entries()) elementRoles.push([concept, [...set]]);
const roleElements = [];
for (const [role, set] of aq.roleElements.entries()) roleElements.push([role, [...set]]);
const aria = [];
for (const [name, def] of aq.aria.entries()) aria.push([name, def]);
const dom = [];
for (const [name, def] of aq.dom.entries()) dom.push([name, def]);

const json = JSON.stringify({ roles, elementRoles, roleElements, aria, dom });
const out = `// GENERATED by packages/aria/scripts/gen-aria-query-data.cjs from aria-query@${pkg.version}.
// Do not edit. aria-query: Apache-2.0, https://github.com/A11yance/aria-query
// Stored as a JSON string: parsed lazily on first use (JSON.parse beats an object literal).

export const ARIA_QUERY_VERSION = ${JSON.stringify(pkg.version)};

export const ARIA_QUERY_DATA = ${JSON.stringify(json)};
`;
fs.writeFileSync(path.join(__dirname, "../src/data/aria-query.generated.ts"), out);
console.log("wrote", out.length, "bytes");
