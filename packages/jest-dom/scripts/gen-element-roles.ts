// Generates src/element-roles.generated.ts from the aria-query version that
// @testing-library/jest-dom@7.0.1 resolves (5.3.2), replicating jest-dom's
// `buildElementRoleList` (src/to-have-role.js): entries sorted by attribute count (stable),
// each entry compiled to a selector `name[attr="v"][attr]:not([attr])`.
//
// Run: node scripts/gen-element-roles.ts
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

const require = createRequire(import.meta.url);
const jestDomDir = dirname(require.resolve("@testing-library/jest-dom/package.json"));
const ariaQueryPkg = createRequire(join(jestDomDir, "package.json")).resolve("aria-query/package.json");
const { elementRoles } = createRequire(ariaQueryPkg)("aria-query");
const version = createRequire(ariaQueryPkg)("./package.json").version;

interface Attr {
  name: string;
  value?: string;
  constraints?: string[];
}

const list: Array<{
  name: string;
  attrs: Array<[string, string]>;
  typeText: boolean;
  roles: string[];
  specificity: number;
}> = [];
for (const [element, roles] of elementRoles.entries()) {
  const attributes: Attr[] = element.attributes ?? [];
  const typeTextIndex = attributes.findIndex((a) => a.value && a.name === "type" && a.value === "text");
  const selectorAttrs = typeTextIndex >= 0 ? attributes.filter((_, i) => i !== typeTextIndex) : attributes;
  list.push({
    name: element.name,
    // [attrName, kind] with kind "=value" (equals), "+" (present) or "-" (absent)
    attrs: selectorAttrs.map(({ name, value, constraints = [] }) => {
      if (constraints.indexOf("undefined") !== -1) return [name, "-"];
      if (value) return [name, "=" + value];
      return [name, "+"];
    }),
    typeText: typeTextIndex >= 0,
    roles: Array.from(roles as Iterable<string>),
    specificity: attributes.length,
  });
}
list.sort((a, b) => b.specificity - a.specificity);

const lines = list.map(
  (e) => `  [${JSON.stringify(e.name)}, ${JSON.stringify(e.attrs)}, ${e.typeText}, ${JSON.stringify(e.roles)}],`,
);
writeFileSync(
  join(import.meta.dirname, "../src/element-roles.generated.ts"),
  `// GENERATED by scripts/gen-element-roles.ts from aria-query@${version} elementRoles — do not edit.
// aria-query is Copyright 2020 A11yance, licensed under the Apache License, Version 2.0
// (http://www.apache.org/licenses/LICENSE-2.0, also in NOTICE); converted to the table below.
// Each entry: [localName, [[attribute, "=value" | "+" (present) | "-" (absent)], ...], requiresTypeText, roles]
// in the order jest-dom@7.0.1's buildElementRoleList produces (stable sort by attribute count, descending).
export type ElementRoleEntry = readonly [string, ReadonlyArray<readonly [string, string]>, boolean, readonly string[]];

export const ELEMENT_ROLES: readonly ElementRoleEntry[] = [
${lines.join("\n")}
];
`,
);
console.log(`wrote ${list.length} entries (aria-query@${version})`);
