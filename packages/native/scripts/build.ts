// `pnpm --filter @rtd/native build`: compile the pure modules into a Node-API addon.
//
//   1. Derive a scriptc library profile from the exported functions of src/lib/rtd.ts whose
//      parameters/results are string / number / boolean / Uint8Array / void.
//   2. `scriptc build --lib --profile` → static archive (dist/build/rtd.lib.a).
//   3. Generate a Node-API C shim from the profile (dist/build/rtd-shim.c).
//   4. clang the shim + archive into dist/rtd-native.node (against Node's own headers).
//
// With --target wasm32-wasi, step 2 builds a WASI reactor instead (dist/rtd.wasm, loaded by
// src/wasm.ts with the profile from step 1) and steps 3–4 are skipped. Needs zig and
// @scriptc/runtime-wasm32-wasi at scriptc's version.
//
// Flags: --optimization <release|speed|dev> (default release), --entry <file> (default src/lib/rtd.ts),
// --target <native|wasm32-wasi> (default native).

import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync, rmSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";

const nativeDir = fileURLToPath(new URL("../", import.meta.url));
const buildDir = join(nativeDir, "dist", "build");
const scriptc = join(nativeDir, "node_modules/.bin/scriptc");

const { values: flags } = parseArgs({
  options: {
    optimization: { type: "string", default: "release" },
    entry: { type: "string", default: "src/lib/rtd.ts" },
    name: { type: "string", default: "rtd" },
    target: { type: "string", default: "native" },
  },
});

type Cls = "f64" | "string" | "bytes" | "bool" | "void";
interface ProfileExport {
  export: string;
  symbol: string;
  params: Cls[];
  returns: Cls;
}

const TYPE_MAP: Record<string, Cls> = {
  number: "f64",
  string: "string",
  boolean: "bool",
  Uint8Array: "bytes",
  void: "void",
};

/** Exported functions with boundary-compatible signatures (a regex is enough for this subset). */
export function deriveExports(source: string, prefix: string): { exports: ProfileExport[]; skipped: string[] } {
  const exports: ProfileExport[] = [];
  const skipped: string[] = [];
  const re = /^export function (\w+)\(([^)]*)\)\s*:\s*([\w[\]| ]+?)\s*\{/gm;
  for (const m of source.matchAll(re)) {
    const [, name, paramText, ret] = m;
    const params = paramText
      .split(",")
      .map((p) => p.trim())
      .filter(Boolean)
      .map((p) => TYPE_MAP[p.split(":")[1]?.trim() ?? ""]);
    const returns = TYPE_MAP[ret.trim()];
    if (!returns || params.some((p) => !p || p === "void")) {
      skipped.push(`${name}(${paramText}): ${ret}`);
      continue;
    }
    const symbol = prefix + name.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);
    exports.push({ export: name, symbol, params, returns });
  }
  return { exports, skipped };
}

function cParams(e: ProfileExport): string {
  const ps: string[] = [];
  e.params.forEach((p, i) => {
    if (p === "f64") ps.push(`double a${i}`);
    else if (p === "bool") ps.push(`bool a${i}`);
    else ps.push(`const uint8_t *a${i}`, `size_t a${i}_len`);
  });
  if (e.returns === "string" || e.returns === "bytes") ps.push("const uint8_t **out", "size_t *out_len");
  return ps.length ? ps.join(", ") : "void";
}

function cReturn(e: ProfileExport): string {
  if (e.returns === "f64") return "double";
  if (e.returns === "bool") return "bool";
  return "void";
}

/** Node-API shim: one napi callback per export; string args go through per-slot growable buffers. */
export function generateShim(prefix: string, exports: ProfileExport[]): string {
  const maxStringArgs = Math.max(1, ...exports.map((e) => e.params.filter((p) => p === "string" || p === "bytes").length));
  const out: string[] = [];
  out.push(
    "// Generated by packages/native/scripts/build.ts — do not edit.",
    "#include <node_api.h>",
    "#include <stdbool.h>",
    "#include <stdint.h>",
    "#include <stdio.h>",
    "#include <stdlib.h>",
    "#include <string.h>",
    "",
    `extern void ${prefix}init(void);`,
    `extern void ${prefix}set_panic_sink(void (*fn)(void *, const uint8_t *, size_t, uint64_t), void *ctx);`,
    `extern void ${prefix}collect(void);`,
  );
  for (const e of exports) out.push(`extern ${cReturn(e)} ${e.symbol}(${cParams(e)});`);
  out.push(
    "",
    "static void sink(void *ctx, const uint8_t *msg, size_t len, uint64_t addr) {",
    "  (void)ctx; (void)addr;",
    '  fprintf(stderr, "rtd-native panic: %.*s\\n", (int)len, (const char *)msg);',
    "  abort();",
    "}",
    "",
    `static char *bufs[${maxStringArgs}];`,
    `static size_t caps[${maxStringArgs}];`,
    "",
    "/* UTF-8 copy of a JS string into slot `slot` (grown as needed). */",
    "static const uint8_t *str_arg(napi_env env, napi_value v, int slot, size_t *len) {",
    "  size_t n = 0;",
    "  napi_get_value_string_utf8(env, v, NULL, 0, &n);",
    "  if (n + 1 > caps[slot]) {",
    "    size_t cap = caps[slot] ? caps[slot] : 4096;",
    "    while (cap < n + 1) cap *= 2;",
    "    bufs[slot] = realloc(bufs[slot], cap);",
    "    caps[slot] = cap;",
    "  }",
    "  napi_get_value_string_utf8(env, v, bufs[slot], caps[slot], len);",
    "  return (const uint8_t *)bufs[slot];",
    "}",
    "",
    "static const uint8_t *bytes_arg(napi_env env, napi_value v, size_t *len) {",
    "  void *data = NULL;",
    "  napi_typedarray_type t; napi_value ab; size_t off;",
    "  napi_get_typedarray_info(env, v, &t, len, &data, &ab, &off);",
    "  return (const uint8_t *)data;",
    "}",
    "",
  );
  const fnName = (e: ProfileExport) => `js_${e.export}`;
  for (const e of exports) {
    out.push(`static napi_value ${fnName(e)}(napi_env env, napi_callback_info info) {`);
    const n = e.params.length;
    out.push(`  size_t argc = ${n}; napi_value argv[${Math.max(1, n)}];`);
    out.push("  napi_get_cb_info(env, info, &argc, argv, NULL, NULL);");
    const args: string[] = [];
    let slot = 0;
    e.params.forEach((p, i) => {
      if (p === "f64") {
        out.push(`  double a${i} = 0; napi_get_value_double(env, argv[${i}], &a${i});`);
        args.push(`a${i}`);
      } else if (p === "bool") {
        out.push(`  bool a${i} = false; napi_get_value_bool(env, argv[${i}], &a${i});`);
        args.push(`a${i}`);
      } else if (p === "string") {
        out.push(`  size_t a${i}_len = 0; const uint8_t *a${i} = str_arg(env, argv[${i}], ${slot++}, &a${i}_len);`);
        args.push(`a${i}`, `a${i}_len`);
      } else {
        out.push(`  size_t a${i}_len = 0; const uint8_t *a${i} = bytes_arg(env, argv[${i}], &a${i}_len);`);
        args.push(`a${i}`, `a${i}_len`);
      }
    });
    out.push("  napi_value r;");
    if (e.returns === "f64") {
      out.push(`  napi_create_double(env, ${e.symbol}(${args.join(", ")}), &r);`);
    } else if (e.returns === "bool") {
      out.push(`  napi_get_boolean(env, ${e.symbol}(${args.join(", ")}), &r);`);
    } else if (e.returns === "string") {
      out.push("  const uint8_t *o = NULL; size_t on = 0;");
      out.push(`  ${e.symbol}(${[...args, "&o", "&on"].join(", ")});`);
      out.push("  napi_create_string_utf8(env, (const char *)o, on, &r);");
    } else if (e.returns === "bytes") {
      out.push("  const uint8_t *o = NULL; size_t on = 0; void *dst = NULL; napi_value ab;");
      out.push(`  ${e.symbol}(${[...args, "&o", "&on"].join(", ")});`);
      out.push("  napi_create_arraybuffer(env, on, &dst, &ab);");
      out.push("  if (on) memcpy(dst, o, on);");
      out.push("  napi_create_typedarray(env, napi_uint8_array, on, ab, 0, &r);");
    } else {
      out.push(`  ${e.symbol}(${args.join(", ")});`);
      out.push("  napi_get_undefined(env, &r);");
    }
    out.push("  return r;", "}", "");
  }
  out.push(
    "static napi_value js_collect(napi_env env, napi_callback_info info) {",
    "  (void)info;",
    `  ${prefix}collect();`,
    "  napi_value r; napi_get_undefined(env, &r); return r;",
    "}",
    "",
    "NAPI_MODULE_INIT() {",
    `  ${prefix}set_panic_sink(sink, NULL);`,
    `  ${prefix}init();`,
    "  napi_property_descriptor d[] = {",
    ...exports.map((e) => `    {"${e.export}", 0, ${fnName(e)}, 0, 0, 0, napi_default, 0},`),
    '    {"collect", 0, js_collect, 0, 0, 0, napi_default, 0},',
    "  };",
    "  napi_define_properties(env, exports, sizeof(d) / sizeof(d[0]), d);",
    "  return exports;",
    "}",
    "",
  );
  return out.join("\n");
}

if (import.meta.main) {
  const entry = join(nativeDir, flags.entry);
  const name = flags.name;
  const prefix = `${name}_`;
  const { exports, skipped } = deriveExports(readFileSync(entry, "utf8"), prefix);
  if (exports.length === 0) throw new Error(`no boundary-compatible exports in ${entry}`);
  for (const s of skipped) console.warn(`skipping (signature can't cross the boundary): ${s}`);

  rmSync(buildDir, { recursive: true, force: true });
  mkdirSync(buildDir, { recursive: true });
  const profile = {
    profile_format: 1,
    name,
    entry: relative(buildDir, entry),
    emission: "llvm",
    ...(flags.optimization !== "release" ? { optimization: flags.optimization } : {}),
    abi: {
      prefix,
      init_symbol: `${prefix}init`,
      sink_register_symbol: `${prefix}set_panic_sink`,
      collect_symbol: `${prefix}collect`,
      result_reset_symbol: null,
    },
    exports,
  };
  const profilePath = join(buildDir, `${name}.profile.json`);
  writeFileSync(profilePath, `${JSON.stringify(profile, null, 2)}\n`);

  if (flags.target === "wasm32-wasi") {
    const wasm = join(nativeDir, "dist", `${name}.wasm`);
    const t = performance.now();
    execFileSync(scriptc, ["build", "--lib", "--profile", profilePath, "-o", wasm], { stdio: "inherit", env: { ...process.env, SCRIPTC_TARGET: "wasm32-wasi" } });
    console.log(`scriptc wasm32-wasi reactor: ${relative(nativeDir, wasm)} (${((performance.now() - t) / 1000).toFixed(1)} s)`);
    process.exit(0);
  }
  if (flags.target !== "native") throw new Error(`--target: native or wasm32-wasi, got ${flags.target}`);

  const archive = join(buildDir, `${name}.lib.a`);
  let t = performance.now();
  execFileSync(scriptc, ["build", "--lib", "--profile", profilePath, "-o", archive], { stdio: "inherit" });
  console.log(`scriptc library: ${relative(nativeDir, archive)} (${((performance.now() - t) / 1000).toFixed(1)} s)`);

  const shimPath = join(buildDir, `${name}-shim.c`);
  writeFileSync(shimPath, generateShim(prefix, exports));
  const nodeInclude = join(dirname(process.execPath), "..", "include", "node");
  const addon = join(nativeDir, "dist", `${name}-native.node`);
  t = performance.now();
  execFileSync(
    "clang",
    ["-O2", "-bundle", "-undefined", "dynamic_lookup", `-I${nodeInclude}`, shimPath, archive, "-o", addon],
    { stdio: "inherit" },
  );
  console.log(`addon: ${relative(nativeDir, addon)} (${((performance.now() - t) / 1000).toFixed(1)} s)`);
  console.log(`exports: ${exports.map((e) => `${e.export}(${e.params.join(", ")}) → ${e.returns}`).join("; ")}`);
}
