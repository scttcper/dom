// Generates entities-data.ts from the WHATWG named character reference table.
// https://html.spec.whatwg.org/#named-character-references
//
// Usage: node packages/dom/src/parser/generate-entities.ts <path/to/entities.json>
// (download https://html.spec.whatwg.org/entities.json first). Not imported at runtime.

import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";

const file = process.argv[2];
if (!file) throw new Error("usage: generate-entities.ts <entities.json>");
const raw = readFileSync(file, "utf8");
const json = JSON.parse(raw) as Record<string, { codepoints: number[]; characters: string }>;
const names = Object.keys(json).sort();

let nameStr = "";
let valueStr = "";
for (const n of names) {
  if (!n.startsWith("&")) throw new Error(n);
  const name = n.slice(1);
  if (!/^[A-Za-z0-9]+;?$/.test(name)) throw new Error(name);
  const chars = json[n].characters;
  if (chars.length > 9) throw new Error("value too long " + n);
  nameStr += (nameStr === "" ? "" : ",") + name;
  valueStr += String(chars.length) + chars;
}

function lit(s: string): string {
  let out = '"';
  for (let i = 0; i < s.length; i++) {
    const c = s.charCodeAt(i);
    if (c >= 0x20 && c < 0x7f && c !== 0x22 && c !== 0x5c) out += s[i];
    else out += "\\u" + c.toString(16).padStart(4, "0");
  }
  return out + '"';
}

const sha = createHash("sha256").update(raw).digest("hex");
const out = `// GENERATED by generate-entities.ts from https://html.spec.whatwg.org/entities.json — do not edit.
// The table is from the HTML Standard, © WHATWG (Apple, Google, Mozilla, Microsoft), licensed
// under CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/); converted to the arrays below.
// Source SHA-256: ${sha}
// https://html.spec.whatwg.org/#named-character-references
//
// ${names.length} entries, sorted. ENTITY_NAMES: comma-separated names without the leading "&"
// (legacy names appear both with and without the trailing ";"). ENTITY_VALUES: for each name in
// the same order, one decimal digit (UTF-16 length) followed by the replacement characters.

export const ENTITY_COUNT = ${names.length};

export const ENTITY_NAMES =
  ${lit(nameStr)};

export const ENTITY_VALUES =
  ${lit(valueStr)};
`;
writeFileSync(new URL("./entities-data.ts", import.meta.url), out);
console.log(names.length, "entities");
