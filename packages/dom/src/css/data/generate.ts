// Generates ./properties.ts from the CSS property definitions jsdom ships (extracted from
// w3c/webref spec data, MIT). Run: node packages/dom/src/css/data/generate.ts
//
// Output per property: name, inherited flag, initial value text (spec form), longhands.

import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";

const require = createRequire(new URL("../../../package.json", import.meta.url));
const jsdomDir = require.resolve("jsdom/package.json").replace(/package\.json$/, "");
const defs: Map<string, { inherited?: string; initial?: string; longhands?: string[] }> = require(jsdomDir + "lib/generated/css-property-definitions.js");

const names = [...defs.keys()].sort();
const lines: string[] = [];
for (const name of names) {
  const d = defs.get(name)!;
  const inherited = d.inherited === "yes" ? 1 : 0;
  let initial = d.initial ?? "";
  if (/see individual|^n\/a|as specified|depends on/i.test(initial)) initial = "";
  const longhands = d.longhands ? d.longhands.join(" ") : "";
  lines.push(`  ${JSON.stringify(name)}, ${inherited}, ${JSON.stringify(initial)}, ${JSON.stringify(longhands)},`);
}

const out = `// GENERATED by ./generate.ts from w3c/webref CSS property data (via jsdom). Do not edit.
//
// Flat table: [name, inherited (0/1), initial value (spec text, "" if none/complex), longhands (space-separated)]...

export const PROPERTY_TABLE: readonly (string | number)[] = [
${lines.join("\n")}
];
`;
writeFileSync(new URL("./properties.ts", import.meta.url), out);
console.log(`wrote ${names.length} properties`);
